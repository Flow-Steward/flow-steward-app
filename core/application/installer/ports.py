"""Ports owned by the installer application service."""

from __future__ import annotations

from collections.abc import Callable, Mapping
from contextlib import AbstractContextManager
from pathlib import Path
from typing import Any, Protocol

from core.application.installer.contracts import (
    BootstrapVerification,
    ImageCurrency,
    InstallationEvidence,
    InstallConfig,
    InstallJournal,
)
from core.application.readiness.contracts import ReadinessReport
from core.application.release.contracts import ReleaseIdentity


class InstallerLog(Protocol):
    path: Path

    def write(self, message: str) -> None: ...

    def close(self) -> None: ...


class InstallerState(Protocol):
    @property
    def journal_path(self) -> Path: ...

    def load_journal(self) -> InstallJournal | None: ...

    def save_journal(self, journal: InstallJournal) -> None: ...

    def clear_journal(self) -> None: ...

    def load_installed_release(self) -> ReleaseIdentity | None: ...

    def load_pending_release(self) -> ReleaseIdentity | None: ...

    def stage_pending_release(self, release: ReleaseIdentity) -> None: ...

    def publish_installed_release(self, release: ReleaseIdentity) -> None: ...

    def open_log(self, operation_id: str) -> InstallerLog: ...

    def operation_lock(self) -> AbstractContextManager[None]: ...


class InstallerGateway(Protocol):
    def inspect(self) -> InstallationEvidence: ...

    def rollback_initial_install(self, journal: InstallJournal, *, log: InstallerLog) -> None: ...

    def preflight(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def update_preflight(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def ensure_configuration(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def ensure_secrets(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def publish_release_environment(
        self, config: InstallConfig, release: ReleaseIdentity
    ) -> None: ...

    def ensure_tls(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def prepare_core(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def start_core(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def verify_schema(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def precheck_migrations(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def ensure_worker_identity(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def activate_worker_identity(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def drop_superseded_worker_credential(
        self, config: InstallConfig, *, log: InstallerLog
    ) -> None: ...

    def refuse_unrecorded_worker_scale(
        self, config: InstallConfig, *, log: InstallerLog
    ) -> None: ...

    def installed_config(self, recorded: InstallConfig) -> InstallConfig: ...

    def take_notices(self) -> tuple[str, ...]: ...

    def record_installed_releases(self, *, current: str, previous: str) -> None: ...

    def set_compact_worker_processes(
        self, config: InstallConfig, *, processes: int, log: InstallerLog
    ) -> InstallConfig: ...

    def set_operator_settings(
        self, config: InstallConfig, *, changes: Mapping[str, str], log: InstallerLog
    ) -> InstallConfig: ...

    def converge_compact_worker_processes(
        self, config: InstallConfig, *, log: InstallerLog, changed: bool = False
    ) -> str: ...

    def start_stopped_services(self, config: InstallConfig, *, log: InstallerLog) -> str: ...

    def unfinished_profile_switch(self) -> dict[str, Any] | None: ...

    def record_switch_host_trees(
        self, installed: InstallConfig, *, log: InstallerLog
    ) -> dict[str, str]: ...

    def normalize_switch_host_trees(
        self, target: InstallConfig, roots: Mapping[str, str], *, log: InstallerLog
    ) -> list[str]: ...

    def restore_switch_worker_token(
        self, installed: InstallConfig, *, log: InstallerLog
    ) -> None: ...

    def check_switch_target_renders(self, target: InstallConfig, *, log: InstallerLog) -> None: ...

    def remove_switch_cli_runtime(self, scalable: InstallConfig, *, log: InstallerLog) -> None: ...

    def remove_switch_source_containers(
        self, source: InstallConfig, target: InstallConfig, *, log: InstallerLog
    ) -> str: ...

    def remove_switch_target_leftovers(
        self, installed: InstallConfig, target: InstallConfig, *, log: InstallerLog
    ) -> None: ...

    def write_switch_pending(self, patch: Any) -> None: ...

    def apply_switch_in_cli(self, scalable: InstallConfig, *, log: InstallerLog) -> None: ...

    def prune_superseded_releases(
        self, config: InstallConfig, *, current: str, previous: str, log: InstallerLog
    ) -> str: ...

    def start_runtime(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def verify_health(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def reconcile_readiness_capabilities(
        self, config: InstallConfig, *, check_ids: tuple[str, ...], log: InstallerLog
    ) -> None: ...

    def verify_storage(
        self, config: InstallConfig, *, log: InstallerLog, read_only: bool = False
    ) -> None: ...

    def verify_public_route(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def verify_bootstrap(
        self, config: InstallConfig, *, log: InstallerLog, require_first_admin: bool = True
    ) -> BootstrapVerification: ...

    def reissue_bootstrap_token(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def capture_initial_manifest(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def ensure_cli_runtime(self, config: InstallConfig, *, log: InstallerLog) -> None: ...

    def postcondition_holds(self, step_id: str, config: InstallConfig) -> bool: ...

    def image_currency(self, config: InstallConfig, *, log: InstallerLog) -> ImageCurrency: ...


ProgressSink = Callable[[str, str, str], Any]
BoundedInstallerReadiness = Callable[[float], ReadinessReport]
