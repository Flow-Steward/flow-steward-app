PROJECT_ROOT = Path(__file__).resolve().parents[4]
_DELEGATED_TEST_RUNTIME_FLAG = "FS_EXTENSION_TEST_RUNTIME"
#: Named by the operator on the command line, not by Core and not in product
#: configuration. An extension owns the name of its own test input; a test input
#: is ephemeral, so it belongs to one invocation rather than to a running system.
_TEST_ENV_OPTION = "--test-env"
#: What "a platform variable" means, in two registers rather than a list kept
#: beside them — a list stops covering the next name somebody adds.
#:
#: The manifest registers what the platform is *configured* with. It is not the
#: whole surface: Core also reads compatibility names that were never registered
#: (`MCP_BEARER_TOKEN`, `POSTGRES_DSN`, `SECRET_KEY`, `AWS_SESSION_TOKEN` and
#: more), and one of those reaching a bundle is the same leak as a registered one.
#: The audit is the surface actually read — every name in `.env.example*`, in
#: Core's Python, shell and compose files, and their retired aliases.
_ENV_MANIFEST_PATH = (
    PROJECT_ROOT / "core" / "infrastructure" / "config" / "flow_steward_env_manifest.json"
)
_ENV_AUDIT_PATH = PROJECT_ROOT / "docs" / "configuration" / "flow-steward-env-audit.json"
_TEST_ENV_NAME_PATTERN = re.compile(r"^[A-Z][A-Z0-9_]*$")
_STANDALONE_ENV_ALLOWLIST = frozenset(
    {
        "CI",
        "COMSPEC",
        "HOME",
        "LANG",
        "LC_ALL",
        "LC_CTYPE",
        "PATH",
        "PATHEXT",
        "REQUESTS_CA_BUNDLE",
        "SSL_CERT_DIR",
        "SSL_CERT_FILE",
        "SYSTEMROOT",
        "TEMP",
        "TERM",
        "TMP",
        "TMPDIR",
        "TZ",
        "USER",
        "WINDIR",
    }
)


def _run(cmd: list[str], *, cwd: Path, env: dict[str, str] | None = None) -> int:
    printable = " ".join(shlex.quote(part) for part in cmd)
    print(f"[run] {printable}", flush=True)
    proc = subprocess.run(
        cmd,
        cwd=str(cwd),
        env=env,
        capture_output=True,
        text=True,
    )
    if proc.stdout:
        print(proc.stdout, end="" if proc.stdout.endswith("\n") else "\n", flush=True)
    if proc.stderr:
        print(proc.stderr, end="" if proc.stderr.endswith("\n") else "\n", flush=True)
    return int(proc.returncode)


@lru_cache(maxsize=1)
def platform_variable_names() -> frozenset[str]:
    """Return every environment variable the platform declares or reads.

    Reading the registers rather than restating them means a name added tomorrow
    is refused tomorrow, with no second list to keep in step. The audit is
    regenerated by a pre-commit hook from the sources it scans, so it cannot
    quietly fall behind the code. An unreadable register refuses everything —
    see the caller.
    """
    names: set[str] = set()

    manifest = json.loads(_ENV_MANIFEST_PATH.read_text(encoding="utf-8"))
    for row in manifest.get("variables") or []:
        if name := str((row or {}).get("name") or "").strip():
            names.add(name)

    audit = json.loads(_ENV_AUDIT_PATH.read_text(encoding="utf-8"))
    audit_rows = audit if isinstance(audit, list) else (audit.get("variables") or [])
    for row in audit_rows:
        row = row if isinstance(row, dict) else {}
        for key in ("variable_name", "canonical_name"):
            if name := str(row.get(key) or "").strip():
                names.add(name)
        for alias in row.get("retired_alias_names") or []:
            if name := str(alias or "").strip():
                names.add(name)

    if not names:
        raise ValueError("the platform variable registers are empty")
    return frozenset(names)


def _reserved_test_env_names() -> frozenset[str]:
    return platform_variable_names()


def requested_test_env_names(requested: Iterable[str] | None) -> list[str]:
    """Return the variable names this run may take from the caller's environment.

    They arrive as repeated `--test-env NAME` options, which is how an extension's
    own integration input — a disposable database DSN, a sandbox base URL —
    reaches its tests without Core knowing that extension's variable names, and
    without leaving a trace in the platform's configuration.

    Anything malformed or reserved is dropped with a reason, because silently
    handing a platform credential to third-party bundle code is the one outcome
    this must not have.
    """
    if not requested:
        return []
    try:
        reserved = _reserved_test_env_names()
    except (OSError, ValueError) as exc:
        # Without the register there is no way to tell a platform secret from an
        # extension's own input, so nothing is handed over.
        print(
            f"[warn] {_TEST_ENV_OPTION}: passing nothing — "
            f"the platform variable register could not be read ({exc})",
            flush=True,
        )
        return []
    names: list[str] = []
    for item in requested:
        name = str(item or "").strip()
        if not name:
            continue
        if not _TEST_ENV_NAME_PATTERN.match(name):
            print(f"[warn] {_TEST_ENV_OPTION}: ignoring malformed name {name!r}", flush=True)
            continue
        if name in reserved:
            print(
                f"[warn] {_TEST_ENV_OPTION}: refusing to pass platform variable {name}",
                flush=True,
            )
            continue
        if name not in names:
            names.append(name)
    return names


def _standalone_test_env(
    extension_dir: Path,
    standalone_python: str,
    *,
    test_env: Iterable[str] | None = None,
) -> dict[str, str]:
    allowed = set(_STANDALONE_ENV_ALLOWLIST) | set(requested_test_env_names(test_env))
    env = {key: value for key, value in _runtime_env.items() if key in allowed}
    env["PYTHONPATH"] = str(extension_dir)
    env["PATH"] = os.pathsep.join((str(Path(standalone_python).parent), str(env.get("PATH") or "")))
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["PYTEST_DISABLE_PLUGIN_AUTOLOAD"] = "1"
    return env


def _pytest_test_env(
    extension_dir: Path,
    standalone_python: str,
    *,
    test_env: Iterable[str] | None = None,
) -> dict[str, str]:
    return _standalone_test_env(extension_dir, standalone_python, test_env=test_env)


def _venv_python(venv_dir: Path) -> str:
    scripts_dir = "Scripts" if os.name == "nt" else "bin"
    return str(venv_dir / scripts_dir / ("python.exe" if os.name == "nt" else "python"))


def _delegated_test_runtime() -> bool:
    value = str(_runtime_env.get(_DELEGATED_TEST_RUNTIME_FLAG, "")).strip().lower()
    return value not in {"", "0", "false"}


@contextmanager
def standalone_python(extension_dir: Path, bundle_name: str) -> Iterator[str | None]:
    """Yield a throwaway interpreter holding the bundle's development requirements.

    The requirements install offline (`pip --no-index`) from the bundle's own
    `dev-wheels/` and `wheels/`. ``None`` means they are missing or did not
    install; the reason is already printed and the caller counts one failure.
    """
    requirements = extension_dir / "requirements-dev.txt"
    if not requirements.exists():
        print(f"[FAIL] standalone requirements missing: {requirements}", flush=True)
    with tempfile.TemporaryDirectory(prefix=f"fs-extension-{bundle_name}-") as tmp:
        venv_dir = Path(tmp) / "venv"
        venv.EnvBuilder(
            with_pip=True,
            clear=True,
            system_site_packages=True,
        ).create(venv_dir)
        python = _venv_python(venv_dir)
        if not requirements.exists():
            yield None
            return
        rc = _run(
            [
                python,
                "-m",
                "pip",
                "install",
                "--disable-pip-version-check",
                "--no-index",
                "--find-links",
                str(extension_dir / "dev-wheels"),
                "--find-links",
                str(extension_dir / "wheels"),
                "-r",
                str(requirements),
            ],
            cwd=extension_dir,
        )
        yield python if rc == 0 else None


def _selected_test_targets(extension_dir: Path, selected: Iterable[str]) -> list[str] | None:
    """Return the requested pytest targets, or ``None`` when one is not in the bundle."""
    root = extension_dir.resolve()
    targets: list[str] = []
    for raw in selected:
        target = str(raw or "").strip()
        if not target:
            continue
        file_part = Path(target.split("::", 1)[0])
        candidate = (root / file_part).resolve()
        if file_part.is_absolute() or not candidate.is_relative_to(root) or not candidate.exists():
            print(f"[FAIL] pytest target is not inside the extension bundle: {target}", flush=True)
            return None
        targets.append(target)
    return targets


def _run_pytest(request: ExtensionTestRequest, extension_dir: Path, python: str) -> int:
    """Run the selected targets fail-fast, or the whole suite to the end; return failures."""
    selected = _selected_test_targets(extension_dir, request.test_paths)
    if selected is None:
        return 1
    tests_dir = extension_dir / "tests"
    targets = selected or (
        [str(path.relative_to(extension_dir)) for path in sorted(tests_dir.glob("test_*.py"))]
        if tests_dir.exists()
        else []
    )
    if targets:
        fail_fast = ["-x"] if selected else []
        rc = _run(
            [python, "-m", "pytest", *fail_fast, *targets],
            cwd=extension_dir,
            env=_pytest_test_env(extension_dir, python, test_env=request.test_env),
        )
        return int(rc != 0)
    if request.allow_no_pytest:
        print(
            f"[warn] no local pytest targets declared for extension={request.extension_id}; explicitly allowed",
            flush=True,
        )
        return 0
    print(
        f"[FAIL] no local pytest targets found for extension={request.extension_id}; add extension/tests or pass --allow-no-pytest",
        flush=True,
    )
    return 1


def _test_extension(request: ExtensionTestRequest) -> int:
    if not _delegated_test_runtime():
        print(
            "[FAIL] extension tests require the dedicated test runtime; "
            "run this command through the installed Flow Steward launcher",
            flush=True,
        )
        return 2
    root = Path(str(request.root or "").strip() or default_extensions_root()).resolve()
    extension_id = str(request.extension_id or "").strip()
    if not extension_id:
        raise SystemExit("extension_id is required")
    bundle_name = (
        extension_folder_name(extension_id)
        if is_canonical_extension_id(extension_id)
        else extension_id
    )
    extension_dir = root / bundle_name
    if not extension_dir.exists():
        print(f"[FAIL] extension folder not found: {extension_dir}", flush=True)
        return 2

    failures = 0

    if not request.skip_validate:
        validation = validate_extensions(
            ExtensionValidationRequest(extension_id=extension_id, root=str(root))
        )
        print(validation.output, end="", flush=True)
        rc = int(validation.exit_code)
        failures += int(rc != 0)

    smoke_script = extension_dir / "scripts" / "smoke_check.py"
    if not request.skip_pytest or (not request.skip_smoke and smoke_script.exists()):
        with standalone_python(extension_dir, bundle_name) as python:
            if python is None:
                failures += 1
            else:
                if not request.skip_smoke and smoke_script.exists():
                    rc = _run(
                        [python, str(smoke_script.relative_to(extension_dir))],
                        cwd=extension_dir,
                        env=_standalone_test_env(extension_dir, python, test_env=request.test_env),
                    )
                    failures += int(rc != 0)
                if not request.skip_pytest:
                    failures += _run_pytest(request, extension_dir, python)
    if failures:
        print(f"[summary] extension={extension_id} ok=false failures={failures}", flush=True)
        return 1
    print(f"[summary] extension={extension_id} ok=true", flush=True)
    return 0


def test_extension(request: ExtensionTestRequest) -> ExtensionTestResult:
    """Run focused extension tests without invoking another CLI parser."""

    command = ExtensionTestRequest.model_validate(request)
    output = io.StringIO()
    with redirect_stdout(output):
        exit_code = _test_extension(command)
    return ExtensionTestResult(
        status="passed" if exit_code == 0 else "failed",
        extension_id=command.extension_id,
        exit_code=exit_code,
        output=output.getvalue(),
    )
