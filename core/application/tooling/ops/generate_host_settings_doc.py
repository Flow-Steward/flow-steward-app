"""Render the public Host settings page from what `config set` accepts.

The page lists every setting an operator changes, by the one name `config set`,
`config show` and the error messages use. Its sources are the ones `config set`
checks -- the `config set` fields and the environment manifest's operator-settable
entries -- and the installer's own options for the Compact examples, so the page
cannot list a name the CLI refuses or miss one it takes.

Usage: python -m core.application.tooling.ops.generate_host_settings_doc [--output PATH]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

from core.application.installer.spec import INSTALLER_SPEC
from core.application.lifecycle.contracts import DeploymentConfig
from core.application.lifecycle.operator_settings import (
    operator_setting_specs,
    typed_setting_fields,
)

HOST_SETTINGS_PATH = Path("docs/configuration/host-settings.md")
#: The one setting an installed Compact changes through ./install.sh besides host
#: settings (AC17-R157).
_COMPACT_INSTALLED_FIELDS = frozenset({"worker_processes"})


def _default(name: str) -> str:
    field = DeploymentConfig.model_fields[name]
    value: Any = field.default_factory() if field.default_factory else field.default  # type: ignore[call-arg]
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (list, tuple)):
        return ", ".join(str(item) for item in value) or "(none)"
    return str(value) if value not in (None, "") else "(empty)"


def _example(field: Any) -> str:
    if field.choices:
        return str(field.choices[0].value)
    if field.examples:
        return str(field.examples[0])
    return "VALUE"


def _typed_section(name: str, field: Any, installer_options: dict[str, str]) -> list[str]:
    allowed = (
        ", ".join(f"`{choice.value}`" for choice in field.choices)
        if field.choices
        else {"integer": "an integer", "path": "a path"}.get(str(field.type), "text")
    )
    value = _example(field)
    lines = [
        f"### `{name}`",
        "",
        field.description or field.label,
        "",
        f"- Default: `{_default(name)}`",
        f"- Accepts: {allowed}",
        f"- Scalable: `flow-steward config set {name}={value}`, then `flow-steward config apply`",
    ]
    option = installer_options.get(name)
    if option and name in _COMPACT_INSTALLED_FIELDS:
        lines.append(f"- Compact: `./install.sh {option} {value}`, also on an installed Compact")
    elif option:
        lines.append(
            f"- Compact: chosen at installation with `./install.sh {option} {value}`; "
            "an installed Compact keeps it"
        )
    else:
        lines.append("- Compact: not set by the operator")
    lines.append("")
    return lines


def _host_section(name: str, spec: Any) -> list[str]:
    allowed = ", ".join(f"`{value}`" for value in spec.allowed_values) or "text"
    value = spec.allowed_values[-1] if spec.allowed_values else "VALUE"
    return [
        f"### `{name}`",
        "",
        spec.notes or "A host setting.",
        "",
        f"- Default: `{spec.default or '(empty)'}`",
        f"- Accepts: {allowed}",
        f"- Scalable: `flow-steward config set {name}={value}`, then `flow-steward config apply`",
        f"- Compact: `./install.sh --setting {name}={value}` from the installation folder; "
        "it keeps the installation and restarts the runtime",
        f"- Reset to the default: `{name}=` (an empty value)",
        "",
    ]


def render_host_settings_markdown() -> str:
    """The page, generated; edit the sources, not the output."""
    installer_options = {
        field.key: field.option_name for field in INSTALLER_SPEC.fields if field.option_name
    }
    lines = [
        "---",
        "# Generated by core/application/tooling/ops/generate_host_settings_doc.py.",
        "# Do not edit: change the config set fields or the environment manifest.",
        "title: Host settings",
        "description: Every setting an operator changes, by the name the CLI accepts.",
        "---",
        "",
        "# Host settings",
        "",
        "Every setting an operator changes has one name. `flow-steward config show`, the",
        "error messages and this page all print it the same way, and",
        "`flow-steward config set NAME=VALUE` accepts it as printed. Several settings are",
        "separated by spaces. A change is staged until `flow-steward config apply`.",
        "",
        "On **Compact**, `config` is not available: a host setting is set with",
        "`./install.sh --setting NAME=VALUE`, which keeps the installation, records the",
        "setting and restarts the runtime.",
        "",
        "## Example: Docling on an internal address",
        "",
        "A Docling service at `http://docling-serve:5001` is a private address, which",
        "Flow Steward refuses by default. The refusal names the setting that allows it and",
        "the command for this installation:",
        "",
        "```bash",
        "# Scalable",
        "flow-steward config set FS_ALLOW_PRIVATE_REMOTE_URLS=1",
        "flow-steward config apply",
        "",
        "# Compact, from the installation folder",
        "./install.sh --setting FS_ALLOW_PRIVATE_REMOTE_URLS=1",
        "```",
        "",
        "Then save the Docling connection again and run the workflow.",
        "",
        "## Host settings",
        "",
        "Environment settings an operator may set by name. Secrets and values the",
        "installer manages are never set this way.",
        "",
    ]
    for name, spec in sorted(operator_setting_specs().items()):
        lines.extend(_host_section(name, spec))
    lines.extend(
        [
            "## Installation settings",
            "",
            "Typed settings of the installation, named as `flow-steward config show` prints",
            "them. The options of `flow-steward config set --help` (`--public-host` for",
            "`public_host`) are synonyms.",
            "",
        ]
    )
    for name, field in typed_setting_fields().items():
        lines.extend(_typed_section(name, field, installer_options))
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Write the page here (the docs site copy); prints it otherwise.",
    )
    args = parser.parse_args(argv)
    text = render_host_settings_markdown()
    if args.output is None:
        sys.stdout.write(text)
    else:
        args.output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
