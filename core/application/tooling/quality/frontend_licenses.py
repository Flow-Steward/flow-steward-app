#!/usr/bin/env python3
"""Licenses and notices of the frontend's production dependencies.

Two rules, both read from ``assets/frontend/package-lock.json``:

1. Every production package has a license on the allowlist. Local links (the
   vendored compatibility shims) carry none and are exempt.
2. Every package in the production closure of a root named in
   ``assets/frontend/third-party-notices.json`` has its section, at the locked
   version and license, in ``assets/frontend/public/third-party-notices.txt``.
   That file ships with the product build and is embedded in the MCP Apps
   report viewer, so the notices travel with the code they cover.

``generate`` writes the notices file from the installed packages' LICENSE and
NOTICE files. ``check`` renders them again from packages installed strictly
from the lockfile (the gate runs ``npm ci --ignore-scripts`` in a scratch copy)
and compares the result with the committed file byte for byte, so a header
kept over a changed or removed license text fails as well.
A product-wide SBOM is a separate concern.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[4]
FRONTEND = Path("assets/frontend")
LOCKFILE = FRONTEND / "package-lock.json"
NOTICE_ROOTS = FRONTEND / "third-party-notices.json"
NOTICES = FRONTEND / "public" / "third-party-notices.txt"

ALLOWED_LICENSES = frozenset(
    {"0BSD", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "MIT", "OFL-1.1"}
)
LICENSE_FILE_NAMES = ("LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "license")
EXTRA_NOTICE_FILES = ("NOTICE", "NOTICE.txt", "CopyrightNotice.txt")
SECTION_RULE = "=" * 72
SECTION_HEADER = re.compile(r"^### (?P<name>\S+) (?P<version>\S+) \((?P<license>[^)]+)\)$", re.M)
HEADER = (
    "Third-party notices for the Flow Steward report renderer\n"
    "Generated by `python -m core.application.tooling.quality.frontend_licenses generate`;\n"
    "do not edit by hand.\n"
)


@dataclass(frozen=True)
class LockedPackage:
    path: str
    name: str
    version: str
    license: str


def _load_lock(root: Path) -> dict[str, dict]:
    lock = json.loads((root / LOCKFILE).read_text(encoding="utf-8"))
    packages = lock.get("packages")
    if not isinstance(packages, dict):
        raise ValueError("package-lock.json has no packages map (lockfile v2 or later)")
    return packages


def _is_production(entry: dict) -> bool:
    return not entry.get("dev") and not entry.get("devOptional")


def _package_name(path: str) -> str:
    return path.rsplit("node_modules/", 1)[-1]


def _resolve(packages: dict[str, dict], from_path: str, dependency: str) -> str | None:
    """Node's lookup: the nearest ``node_modules/<dependency>`` walking up from *from_path*."""
    base = from_path
    while True:
        candidate = f"{base}/node_modules/{dependency}" if base else f"node_modules/{dependency}"
        if candidate in packages:
            return candidate
        if not base:
            return None
        cut = base.rfind("/node_modules/")
        base = base[:cut] if cut >= 0 else ""


def production_closure(packages: dict[str, dict], roots: Iterable[str]) -> list[LockedPackage]:
    """Every package a production root pulls in, in a stable order."""
    seen: dict[str, LockedPackage] = {}
    pending = [path for root in roots if (path := _resolve(packages, "", root))]
    while pending:
        path = pending.pop()
        if path in seen:
            continue
        entry = packages[path]
        seen[path] = LockedPackage(
            path=path,
            name=_package_name(path),
            version=str(entry.get("version") or ""),
            license=str(entry.get("license") or ""),
        )
        # Peers belong to the host application, not to this closure.
        wanted = {**entry.get("dependencies", {}), **entry.get("optionalDependencies", {})}
        for dependency in wanted:
            resolved = _resolve(packages, path, dependency)
            if resolved:
                pending.append(resolved)
    return sorted(seen.values(), key=lambda item: (item.name, item.version, item.path))


def license_problems(packages: dict[str, dict]) -> list[str]:
    problems = []
    for path, entry in sorted(packages.items()):
        if not path or not _is_production(entry) or entry.get("link"):
            continue
        license_id = str(entry.get("license") or "")
        if license_id not in ALLOWED_LICENSES:
            problems.append(
                f"{_package_name(path)}@{entry.get('version')}: license {license_id or '(none)'} "
                "is not on the allowlist"
            )
    return problems


def _notice_roots(root: Path) -> list[str]:
    roots = json.loads((root / NOTICE_ROOTS).read_text(encoding="utf-8")).get("roots")
    if not isinstance(roots, list) or not all(isinstance(item, str) for item in roots):
        raise ValueError(f"{NOTICE_ROOTS} needs a list of package names under 'roots'")
    return roots


def _unique(packages: list[LockedPackage]) -> list[LockedPackage]:
    """One section per name, version and license, however often it is installed."""
    unique: dict[tuple[str, str, str], LockedPackage] = {}
    for package in packages:
        unique.setdefault((package.name, package.version, package.license), package)
    return list(unique.values())


def _sections(text: str) -> dict[str, str]:
    """Notice sections by their ``### name version (license)`` header line."""
    sections: dict[str, str] = {}
    for block in text.split(SECTION_RULE)[1:]:
        header = SECTION_HEADER.search(block)
        if header:
            sections[header.group(0)] = block.strip()
    return sections


def notice_problems(root: Path, modules: Path) -> list[str]:
    """The committed notices must equal those rendered from the locked packages, byte for byte.

    A section whose header survives but whose license or notice text was
    changed or removed is a difference like any other.
    """
    notices_path = root / NOTICES
    if not notices_path.is_file():
        return [f"{NOTICES} is missing; run the generate command"]
    expected_text = render_notices(root, modules)
    actual_text = notices_path.read_text(encoding="utf-8")
    if actual_text == expected_text:
        return []
    expected, actual = _sections(expected_text), _sections(actual_text)
    problems = [
        f"{NOTICES}: no notice for {header[4:]}; run the generate command"
        for header in sorted(expected.keys() - actual.keys())
    ]
    problems.extend(
        f"{NOTICES}: {header[4:]} is not in the locked closure; regenerate"
        for header in sorted(actual.keys() - expected.keys())
    )
    problems.extend(
        f"{NOTICES}: the text for {header[4:]} differs from the locked package's files; regenerate"
        for header in sorted(expected.keys() & actual.keys())
        if expected[header] != actual[header]
    )
    return problems or [f"{NOTICES} differs from the rendered notices; regenerate"]


def _package_directory(root: Path, modules: Path | None, package: LockedPackage) -> Path:
    """Where a locked package is installed: under *modules* when given, else the checkout."""
    if modules is None:
        return root / FRONTEND / package.path
    return modules / package.path.split("node_modules/", 1)[1]


def _read_text_files(directory: Path, names: Iterable[str]) -> list[tuple[str, str]]:
    return [
        (name, (directory / name).read_text(encoding="utf-8").strip())
        for name in names
        if (directory / name).is_file()
    ]


def _subcomponent_licenses(directory: Path) -> list[tuple[str, str]]:
    """Licenses of bundled subcomponents, such as ECharts' ``licenses/LICENSE-d3``."""
    licenses_dir = directory / "licenses"
    if not licenses_dir.is_dir():
        return []
    return [
        (f"licenses/{path.name}", path.read_text(encoding="utf-8").strip())
        for path in sorted(licenses_dir.iterdir())
        if path.is_file()
    ]


def render_notices(root: Path, modules: Path | None = None) -> str:
    packages = _unique(production_closure(_load_lock(root), _notice_roots(root)))
    sections = [HEADER]
    for package in packages:
        directory = _package_directory(root, modules, package)
        license_files = _read_text_files(directory, LICENSE_FILE_NAMES)[:1]
        if not license_files:
            raise FileNotFoundError(f"{package.name}: no LICENSE file in {directory}")
        parts = [SECTION_RULE, f"### {package.name} {package.version} ({package.license})", ""]
        extras = [
            *_read_text_files(directory, EXTRA_NOTICE_FILES),
            *_subcomponent_licenses(directory),
        ]
        for name, text in [*license_files, *extras]:
            parts.extend([f"--- {name} ---", text, ""])
        sections.append("\n".join(parts))
    return "\n".join(sections).rstrip("\n") + "\n"


def cmd_check(root: Path, modules: Path) -> int:
    if not modules.is_dir():
        print(f"ERROR: {modules} is not an installed node_modules directory")
        return 2
    problems = [*license_problems(_load_lock(root)), *notice_problems(root, modules)]
    for problem in problems:
        print(f"ERROR: {problem}")
    if problems:
        return 1
    print("OK: frontend production licenses are allowed and notices are complete")
    return 0


def cmd_generate(root: Path, modules: Path | None = None) -> int:
    (root / NOTICES).write_text(render_notices(root, modules), encoding="utf-8")
    print(f"Wrote {NOTICES}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("command", choices=("check", "generate"))
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    parser.add_argument(
        "--modules",
        type=Path,
        help="node_modules installed from the lockfile (check: required; generate: default the checkout's)",
    )
    args = parser.parse_args(argv)
    root = args.root.resolve()
    if args.command == "generate":
        return cmd_generate(root, args.modules)
    if args.modules is None:
        parser.error("check needs --modules: the packages installed from the lockfile")
    return cmd_check(root, args.modules.resolve())


if __name__ == "__main__":
    sys.exit(main())
