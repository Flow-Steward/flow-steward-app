"""Auth API route registration helpers for the FastAPI app."""

from __future__ import annotations

from fastapi import FastAPI

from core.entrypoints.api.auth_passwords import create_auth_passwords_router
from core.entrypoints.api.auth_sessions import create_auth_sessions_router
from core.entrypoints.api.auth_tokens_accounts import create_auth_tokens_accounts_router
from core.entrypoints.api.auth_users import create_auth_users_router


def register_auth_routes(
    app: FastAPI,
    *,
    local_auth_enabled,
    external_auth_enabled,
    get_logger_only,
    auth_tables_available,
    auth_pat_tables_available,
    auth_account_tables_available,
    auth_service_account_tables_available,
    auth_machine_token_tables_available,
    auth_password_reset_tables_available,
    auth_user_column_exists,
    require_authenticated_user,
    request_auth_user_payload,
    request_scope,
    request_principal,
    api_error_response,
    service_error_response,
    log_auth_audit_event,
    auth_login_clear_user_failures,
    get_user_by_id,
    get_user_by_username,
    normalize_requested_roles,
    seed_default_roles,
    password_hash,
    verify_password,
    request_auth_token,
    session_token_hash,
    request_client_ip,
    password_reset_enabled,
    password_reset_throttle_check,
    password_reset_throttle_record,
    password_reset_token_hash,
    auth_user_deleted_condition,
    real_dict_cursor_kwargs,
    dispatch_password_reset_email,
    password_reset_debug_reveal_token,
    resolve_actor_username,
    auth_cookie_secure,
    bootstrap_request_allowed,
    auth_login_lock_state,
    auth_login_record_failure,
    auth_login_clear_failures,
    csrf_request_valid,
    sql_user_username_column,
    sql_update_user_password_by_id,
    sql_limit_1,
    auth_admin_roles,
    auth_password_min_length,
    auth_password_reset_ttl_minutes,
    auth_session_ttl_hours,
    auth_remember_session_ttl_hours,
    auth_cookie_name,
    auth_csrf_cookie_name,
    err_authentication_required,
    err_database_not_configured,
    err_auth_tables_not_available,
    err_admin_role_required,
    err_local_auth_disabled,
    err_invalid_json_body,
    err_username_required,
    err_pat_tables_not_available,
    err_token_not_found,
    err_account_tables_not_available,
    err_service_account_key_required,
    err_machine_token_tables_not_available,
    err_password_reset_flow_disabled,
    err_auth_password_reset_tables_not_available,
    err_account_disabled,
    err_too_many_password_reset_requests,
    err_too_many_login_attempts,
    first_admin_service_factory,
):
    _ = (
        request_scope,
        request_principal,
        service_error_response,
    )
    auth_users_router = create_auth_users_router(
        local_auth_enabled=local_auth_enabled,
        external_auth_enabled=external_auth_enabled,
        get_logger_only=get_logger_only,
        auth_tables_available=auth_tables_available,
        require_authenticated_user=require_authenticated_user,
        request_auth_user_payload=request_auth_user_payload,
        api_error_response=api_error_response,
        log_auth_audit_event=log_auth_audit_event,
        auth_login_clear_user_failures=auth_login_clear_user_failures,
        get_user_by_id=get_user_by_id,
        get_user_by_username=get_user_by_username,
        normalize_requested_roles=normalize_requested_roles,
        seed_default_roles=seed_default_roles,
        password_hash=password_hash,
        auth_user_column_exists=auth_user_column_exists,
        real_dict_cursor_kwargs=real_dict_cursor_kwargs,
        auth_admin_roles=auth_admin_roles,
        err_authentication_required=err_authentication_required,
        err_database_not_configured=err_database_not_configured,
        err_auth_tables_not_available=err_auth_tables_not_available,
        err_admin_role_required=err_admin_role_required,
        err_local_auth_disabled=err_local_auth_disabled,
        err_invalid_json_body=err_invalid_json_body,
        auth_csrf_cookie_name=auth_csrf_cookie_name,
    )
    app.include_router(auth_users_router)

    auth_tokens_accounts_router = create_auth_tokens_accounts_router(
        local_auth_enabled=local_auth_enabled,
        get_logger_only=get_logger_only,
        auth_tables_available=auth_tables_available,
        auth_pat_tables_available=auth_pat_tables_available,
        auth_account_tables_available=auth_account_tables_available,
        auth_service_account_tables_available=auth_service_account_tables_available,
        auth_machine_token_tables_available=auth_machine_token_tables_available,
        require_authenticated_user=require_authenticated_user,
        api_error_response=api_error_response,
        log_auth_audit_event=log_auth_audit_event,
        auth_admin_roles=auth_admin_roles,
        err_local_auth_disabled=err_local_auth_disabled,
        err_database_not_configured=err_database_not_configured,
        err_auth_tables_not_available=err_auth_tables_not_available,
        err_pat_tables_not_available=err_pat_tables_not_available,
        err_authentication_required=err_authentication_required,
        err_token_not_found=err_token_not_found,
        err_account_tables_not_available=err_account_tables_not_available,
        err_admin_role_required=err_admin_role_required,
        err_service_account_key_required=err_service_account_key_required,
        err_machine_token_tables_not_available=err_machine_token_tables_not_available,
    )
    app.include_router(auth_tokens_accounts_router)

    auth_passwords_router = create_auth_passwords_router(
        local_auth_enabled=local_auth_enabled,
        password_reset_enabled=password_reset_enabled,
        get_logger_only=get_logger_only,
        auth_tables_available=auth_tables_available,
        auth_password_reset_tables_available=auth_password_reset_tables_available,
        auth_user_column_exists=auth_user_column_exists,
        require_authenticated_user=require_authenticated_user,
        get_user_by_username=get_user_by_username,
        verify_password=verify_password,
        password_hash=password_hash,
        request_auth_token=request_auth_token,
        session_token_hash=session_token_hash,
        request_client_ip=request_client_ip,
        password_reset_throttle_check=password_reset_throttle_check,
        password_reset_throttle_record=password_reset_throttle_record,
        password_reset_token_hash=password_reset_token_hash,
        auth_user_deleted_condition=auth_user_deleted_condition,
        real_dict_cursor_kwargs=real_dict_cursor_kwargs,
        dispatch_password_reset_email=dispatch_password_reset_email,
        password_reset_debug_reveal_token=password_reset_debug_reveal_token,
        auth_login_clear_user_failures=auth_login_clear_user_failures,
        resolve_actor_username=resolve_actor_username,
        api_error_response=api_error_response,
        log_auth_audit_event=log_auth_audit_event,
        sql_update_user_password_by_id=sql_update_user_password_by_id,
        sql_user_username_column=sql_user_username_column,
        sql_limit_1=sql_limit_1,
        auth_password_min_length=auth_password_min_length,
        auth_password_reset_ttl_minutes=auth_password_reset_ttl_minutes,
        err_local_auth_disabled=err_local_auth_disabled,
        err_password_reset_flow_disabled=err_password_reset_flow_disabled,
        err_database_not_configured=err_database_not_configured,
        err_auth_tables_not_available=err_auth_tables_not_available,
        err_auth_password_reset_tables_not_available=err_auth_password_reset_tables_not_available,
        err_authentication_required=err_authentication_required,
        err_account_disabled=err_account_disabled,
        err_username_required=err_username_required,
        err_too_many_password_reset_requests=err_too_many_password_reset_requests,
    )
    app.include_router(auth_passwords_router)

    auth_sessions_router = create_auth_sessions_router(
        get_logger_only=get_logger_only,
        session_token_hash=session_token_hash,
        auth_cookie_secure=auth_cookie_secure,
        log_auth_audit_event=log_auth_audit_event,
        local_auth_enabled=local_auth_enabled,
        bootstrap_request_allowed=bootstrap_request_allowed,
        auth_tables_available=auth_tables_available,
        resolve_actor_username=resolve_actor_username,
        get_user_by_username=get_user_by_username,
        request_client_ip=request_client_ip,
        auth_login_lock_state=auth_login_lock_state,
        auth_login_record_failure=auth_login_record_failure,
        verify_password=verify_password,
        password_hash=password_hash,
        auth_user_column_exists=auth_user_column_exists,
        auth_login_clear_failures=auth_login_clear_failures,
        csrf_request_valid=csrf_request_valid,
        api_error_response=api_error_response,
        err_database_not_configured=err_database_not_configured,
        err_local_auth_disabled=err_local_auth_disabled,
        err_auth_tables_not_available=err_auth_tables_not_available,
        err_too_many_login_attempts=err_too_many_login_attempts,
        auth_password_min_length=auth_password_min_length,
        auth_session_ttl_hours=auth_session_ttl_hours,
        auth_remember_session_ttl_hours=auth_remember_session_ttl_hours,
        auth_cookie_name=auth_cookie_name,
        auth_csrf_cookie_name=auth_csrf_cookie_name,
        first_admin_service_factory=first_admin_service_factory,
    )
    app.include_router(auth_sessions_router)

    return auth_users_router
