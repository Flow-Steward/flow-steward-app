"""Tab completion scripts for bash, zsh and fish, generated from the public command tree.

Pressing Tab must not start Docker: the host launcher runs every command in a container,
which takes seconds. So the scripts are static -- commands, subcommands, options and
fixed choices are written out once from the same Click tree the CLI runs -- and kept in
``core/entrypoints/cli/completion/``, where the host launcher and the Compact image
print them without Python. A unit test regenerates them and fails when they drift.

Regenerate after changing a command::

    python -m core.entrypoints.cli.platform.completion write
"""

from __future__ import annotations

import sys
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path

import click

PROGRAM = "flow-steward"
SHELLS = ("bash", "zsh", "fish")
COMPLETION_DIR = Path(__file__).resolve().parents[1] / "completion"
_HEADER = "Generated by core/entrypoints/cli/platform/completion.py; do not edit."


@dataclass(frozen=True)
class OptionInfo:
    names: tuple[str, ...]
    help: str
    takes_value: bool
    choices: tuple[str, ...] = ()


@dataclass(frozen=True)
class CommandInfo:
    """One command word: a group (with children) or an executable leaf (with options)."""

    name: str
    help: str
    children: tuple[CommandInfo, ...] = ()
    options: tuple[OptionInfo, ...] = field(default=())


def _first_line(text: str | None) -> str:
    line = (text or "").strip().splitlines()[0] if (text or "").strip() else ""
    return line.rstrip(".")


def _options(command: click.Command) -> tuple[OptionInfo, ...]:
    found: list[OptionInfo] = []
    for param in command.params:
        if not isinstance(param, click.Option) or param.hidden:
            continue
        names = tuple(
            name for name in (*param.opts, *param.secondary_opts) if name.startswith("--")
        )
        if not names:
            continue
        choices = (
            tuple(str(choice) for choice in param.type.choices)
            if isinstance(param.type, click.Choice)
            else ()
        )
        found.append(
            OptionInfo(
                names=names,
                help=_first_line(param.help),
                takes_value=not param.is_flag and not param.count,
                choices=choices,
            )
        )
    found.append(OptionInfo(names=("--help",), help="Show help", takes_value=False))
    return tuple(found)


def command_tree(root: click.Group | None = None) -> CommandInfo:
    """The public tree as plain data; built from the real Click app by default."""
    if root is None:
        from core.entrypoints.cli.platform.click_adapter import build_click_app

        root = build_click_app(None, None)

    def describe(name: str, command: click.Command) -> CommandInfo:
        if isinstance(command, click.Group):
            children = tuple(
                describe(child_name, command.commands[child_name])
                for child_name in sorted(command.commands)
            )
            summaries = ", ".join(child.name for child in children)
            return CommandInfo(
                name=name,
                help=f"{name.replace('-', ' ').capitalize()}: {summaries}",
                children=children,
                options=_options(command),
            )
        return CommandInfo(
            name=name,
            help=_first_line(command.short_help or command.help),
            options=_options(command),
        )

    return describe(PROGRAM, root)


def _leaves(tree: CommandInfo) -> Iterable[tuple[str, CommandInfo]]:
    for child in tree.children:
        if child.children:
            for leaf in child.children:
                yield f"{child.name} {leaf.name}", leaf
        else:
            yield child.name, child


def _words(values: Iterable[str]) -> str:
    return " ".join(values)


# --- bash -----------------------------------------------------------------------------------


def render_bash(tree: CommandInfo) -> str:
    groups = [child for child in tree.children if child.children]
    lines = [
        f"# Tab completion for {PROGRAM} (bash). {_HEADER}",
        f'# Enable: eval "$({PROGRAM} completion bash)"   (or ./{PROGRAM} completion bash)',
        "_FLOW_STEWARD_COMMANDS=(" + " ".join(child.name for child in tree.children) + ")",
        "_flow_steward_complete() {",
        '    local cur="${COMP_WORDS[COMP_CWORD]}" prev="${COMP_WORDS[COMP_CWORD-1]}"',
        '    local i word group="" leaf=""',
        "    for ((i = 1; i < COMP_CWORD; i++)); do",
        '        word="${COMP_WORDS[i]}"',
        '        case "$word" in -*) continue ;; esac',
        '        if [[ -z "$group" ]]; then group="$word"',
        '        elif [[ -z "$leaf" ]]; then leaf="$word"; fi',
        "    done",
        '    local key="$group${leaf:+ $leaf}" words=""',
        '    case "$key|$prev" in',
    ]
    for key, leaf in _leaves(tree):
        for option in leaf.options:
            if option.choices:
                for name in option.names:
                    lines.append(f'        "{key}|{name}") words="{_words(option.choices)}" ;;')
    lines += [
        "    esac",
        '    if [[ -n "$words" ]]; then',
        '        COMPREPLY=($(compgen -W "$words" -- "$cur")); return',
        "    fi",
        '    if [[ -z "$group" && "$cur" != -* ]]; then',
        f'        COMPREPLY=($(compgen -W "{_words(child.name for child in tree.children)}" -- "$cur")); return',
        "    fi",
        '    case "$group" in',
    ]
    for group in groups:
        lines.append(
            f'        {group.name}) if [[ -z "$leaf" && "$cur" != -* ]]; then '
            f'COMPREPLY=($(compgen -W "{_words(c.name for c in group.children)}" -- "$cur")); '
            "return; fi ;;"
        )
    lines += ["    esac", '    case "$key" in']
    for key, leaf in _leaves(tree):
        names = _words(name for option in leaf.options for name in option.names)
        lines.append(f'        "{key}") words="{names}" ;;')
    root_options = _words(name for option in tree.options for name in option.names)
    lines += [
        f'        *) words="{root_options}" ;;',
        "    esac",
        '    if [[ "$cur" == -* ]]; then',
        '        COMPREPLY=($(compgen -W "$words" -- "$cur"))',
        "    fi",
        "}",
        f"complete -o default -F _flow_steward_complete {PROGRAM}",
        "",
    ]
    return "\n".join(lines)


# --- zsh ------------------------------------------------------------------------------------


def _zsh_item(name: str, help_text: str) -> str:
    text = help_text.replace("\\", "\\\\").replace(":", "\\:").replace("'", "'\\''")
    return f"'{name}:{text}'" if text else f"'{name}'"


def render_zsh(tree: CommandInfo) -> str:
    groups = [child for child in tree.children if child.children]
    lines = [
        f"#compdef {PROGRAM}",
        f"# Tab completion for {PROGRAM} (zsh). {_HEADER}",
        f'# Enable: eval "$({PROGRAM} completion zsh)"   (or ./{PROGRAM} completion zsh)',
        "_flow_steward() {",
        '    local i word group="" leaf="" prev="${words[CURRENT-1]}"',
        "    for (( i = 2; i < CURRENT; i++ )); do",
        '        word="${words[i]}"',
        '        [[ "$word" == -* ]] && continue',
        '        if [[ -z "$group" ]]; then group="$word"',
        '        elif [[ -z "$leaf" ]]; then leaf="$word"; fi',
        "    done",
        '    local key="$group${leaf:+ $leaf}"',
        "    local -a items",
        '    case "$key|$prev" in',
    ]
    for key, leaf in _leaves(tree):
        for option in leaf.options:
            if option.choices:
                for name in option.names:
                    lines.append(
                        f'        "{key}|{name}") compadd -- {_words(option.choices)}; return ;;'
                    )
    lines += [
        "    esac",
        '    if [[ -z "$group" && "${words[CURRENT]}" != -* ]]; then',
        "        items=(" + " ".join(_zsh_item(c.name, c.help) for c in tree.children) + ")",
        "        _describe 'command' items; return",
        "    fi",
        '    case "$group" in',
    ]
    for group in groups:
        items = " ".join(_zsh_item(c.name, c.help) for c in group.children)
        lines.append(
            f'        {group.name}) if [[ -z "$leaf" && "${{words[CURRENT]}}" != -* ]]; then '
            f"items=({items}); _describe '{group.name} command' items; return; fi ;;"
        )
    lines += ["    esac", '    case "$key" in']
    for key, leaf in _leaves(tree):
        items = " ".join(
            _zsh_item(name, option.help) for option in leaf.options for name in option.names
        )
        lines.append(f'        "{key}") items=({items}) ;;')
    root_items = " ".join(
        _zsh_item(name, option.help) for option in tree.options for name in option.names
    )
    lines += [
        f"        *) items=({root_items}) ;;",
        "    esac",
        '    if [[ "${words[CURRENT]}" == -* ]]; then',
        "        _describe 'option' items",
        "    else",
        "        _files",
        "    fi",
        "}",
        "(( $+functions[compdef] )) || { autoload -Uz compinit && compinit; }",
        f"compdef _flow_steward {PROGRAM}",
        f"compdef -p _flow_steward '*/{PROGRAM}'",
        "",
    ]
    return "\n".join(lines)


# --- fish -----------------------------------------------------------------------------------


def _fish_quote(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def render_fish(tree: CommandInfo) -> str:
    roots = " ".join(child.name for child in tree.children)
    lines = [
        f"# Tab completion for {PROGRAM} (fish). {_HEADER}",
        f"# Enable: {PROGRAM} completion fish | source",
        f"complete -c {PROGRAM} -f",
    ]
    for child in tree.children:
        lines.append(
            f"complete -c {PROGRAM} -n 'not __fish_seen_subcommand_from {roots}' "
            f"-a {child.name} -d {_fish_quote(child.help)}"
        )
    for group in (child for child in tree.children if child.children):
        subs = " ".join(c.name for c in group.children)
        for sub in group.children:
            lines.append(
                f"complete -c {PROGRAM} -n '__fish_seen_subcommand_from {group.name}; "
                f"and not __fish_seen_subcommand_from {subs}' -a {sub.name} "
                f"-d {_fish_quote(sub.help)}"
            )
    for key, leaf in _leaves(tree):
        words = key.split()
        condition = "; and ".join(f"__fish_seen_subcommand_from {word}" for word in words)
        for option in leaf.options:
            for name in option.names:
                line = f"complete -c {PROGRAM} -n '{condition}' -l {name.removeprefix('--')}"
                if option.help:
                    line += f" -d {_fish_quote(option.help)}"
                if option.choices:
                    line += f" -x -a {_fish_quote(' '.join(option.choices))}"
                elif option.takes_value:
                    line += " -r -F"
                lines.append(line)
    lines.append("")
    return "\n".join(lines)


RENDERERS = {"bash": render_bash, "zsh": render_zsh, "fish": render_fish}


def render(shell: str, tree: CommandInfo | None = None) -> str:
    return RENDERERS[shell](tree or command_tree())


def write(directory: Path = COMPLETION_DIR) -> list[Path]:
    tree = command_tree()
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for shell in SHELLS:
        path = directory / f"{PROGRAM}.{shell}"
        path.write_text(render(shell, tree), encoding="utf-8")
        written.append(path)
    return written


if __name__ == "__main__":
    if sys.argv[1:] != ["write"]:
        raise SystemExit("usage: python -m core.entrypoints.cli.platform.completion write")
    for written_path in write():
        print(written_path)
