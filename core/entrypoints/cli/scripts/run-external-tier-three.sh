#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd -- "${SCRIPT_DIR}/../../../.." && pwd)"
# shellcheck source=core/entrypoints/cli/scripts/docker_compose_env.sh
source "${SCRIPT_DIR}/docker_compose_env.sh"

dry_run=0
verify_args=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --dry-run)
      dry_run=1
      ;;
    --evidence-mode|--fingerprint-source|--trust|--commit-sha)
      option="$1"
      shift
      if [[ $# -eq 0 ]]; then
        echo "${option} requires a value." >&2
        exit 2
      fi
      verify_args+=("${option}" "$1")
      ;;
    *)
      echo "Unsupported external Tier 3 argument: $1" >&2
      exit 2
      ;;
  esac
  shift
done

# This internal selector is generated by canonical lint after its toolchain
# guard. Dry-run validates its shape without reaching the Docker daemon.
if [[ ! "${FS_TEST_AUDIT_IMAGE_ID:-}" =~ ^sha256:[0-9a-f]{64}$ ]]; then
  echo "FS_TEST_AUDIT_IMAGE_ID must be a full immutable image ID; invoke canonical lint.sh." >&2
  exit 2
fi

git_common_dir="${FS_EXTERNAL_TIER_GIT_COMMON_DIR:-}"
if [[ -z "${git_common_dir}" ]]; then
  git_common_dir="$(git -C "${ROOT_DIR}" rev-parse --path-format=absolute --git-common-dir)"
fi
oauth_project="fs-oauth-generic-full-${BASHPID:-$$}"
# The repository stack env belongs to the caller's regular Compose project and may
# contain FS_COMPOSE_PROJECT_NAME.  Do not let it overwrite the unique project name
# injected below when lint.sh is sourced inside this external-check container.
external_stack_env="/tmp/flow-steward-external-tier-three-no-stack-env"
command=(
  fs_compose run --no-deps --rm -T --user 0:0
  -e "FS_COMPOSE_PROJECT_NAME=${oauth_project}"
  -e "FS_TEST_AUDIT_IMAGE_ID=${FS_TEST_AUDIT_IMAGE_ID}"
  -e "FS_STACK_ENV_FILE=${external_stack_env}"
  -v /var/run/docker.sock:/var/run/docker.sock
  -v "${git_common_dir}:${git_common_dir}:ro"
  fs-audit python -m core.application.tooling.quality.verify
  --tier 3 --execution external --repository-root /app
  "${verify_args[@]}"
)

if [[ "${dry_run}" -eq 1 ]]; then
  printf '%q ' "${command[@]}"
  printf '\n'
  exit 0
fi

fs_compose run --no-deps --rm -T --user 0:0 \
  -e "FS_COMPOSE_PROJECT_NAME=${oauth_project}" \
  -e "FS_TEST_AUDIT_IMAGE_ID=${FS_TEST_AUDIT_IMAGE_ID}" \
  -e "FS_STACK_ENV_FILE=${external_stack_env}" \
  -v /var/run/docker.sock:/var/run/docker.sock \
  -v "${git_common_dir}:${git_common_dir}:ro" \
  fs-audit python -m core.application.tooling.quality.verify \
  --tier 3 --execution external --repository-root /app \
  "${verify_args[@]}"
