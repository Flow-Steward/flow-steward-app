"""Durable task and workflow-resume publication with confirmation semantics."""

import contextlib
import json
import logging
from typing import Any

from core.infrastructure.runtime.worker.queue_broker import (
    _EXCHANGE,
    _READY_QUEUE,
    _TOKEN_APPLICATION_JSON,
    _connect,
    _declare_queue,
    _declare_ready_queue,
    _publish_ready_hint,
    _queue_name,
)
from core.infrastructure.runtime.worker.queue_lease_store import (
    normalize_entity_id as _normalize_entity_id,
)
from core.infrastructure.runtime.worker.queue_messages import (
    _json_default,
    _sanitize_project_config_for_queue,
)
from core.infrastructure.runtime.worker.queue_pika_compat import pika

logger = logging.getLogger(__name__)


class QueuePublishNotSentError(RuntimeError):
    """RabbitMQ setup failed before a project message could be published."""

    queue_dispatch_outcome = "not_sent"


def enqueue_task(
    project_id: Any,
    job_id: Any,
    task_id: str,
    task_summary: str,
    task_source: str,
    project_name: str,
    project_config: dict,
    thread_id: str,
    mode: str | None = None,
    extra_state: dict | None = None,
    amqp_url: str | None = None,
) -> None:
    """
    Publish one task message to the project's RabbitMQ queue.
    The message is persistent and will survive broker restarts.
    Raises RuntimeError if the broker is unreachable.

    thread_id is the LangGraph checkpoint key (UUID per run). Callers must pass
    the unique UUID generated by enqueue runtime so every retry starts from a
    clean checkpoint and the /api/approvals/{thread_id} URL matches the
    checkpoint stored by the worker.
    """
    project_id = _normalize_entity_id(project_id)
    job_id = _normalize_entity_id(job_id)
    clean_thread_id = str(thread_id or "").strip()
    if not clean_thread_id:
        raise ValueError("thread_id is required for queue task messages")
    message = {
        "job_id": job_id,
        "task_id": task_id,
        "thread_id": clean_thread_id,
        "task_summary": task_summary,
        "task_source": task_source,
        "project_id": project_id,
        "project_name": project_name,
        "project_config": _sanitize_project_config_for_queue(project_config),
        "mode": mode,
        "extra_state": extra_state or {},
    }
    body = json.dumps(message, default=_json_default).encode()

    conn = None
    try:
        try:
            conn = _connect(amqp_url)
            ch = conn.channel()
            _declare_queue(ch, project_id)
            _declare_ready_queue(ch)
            # Publisher confirms keep the DB job row and RabbitMQ state in sync.
            # Pika's basic_publish does not have a reliable boolean return contract,
            # so we fail closed on broker-side publish exceptions instead.
            ch.confirm_delivery()
        except Exception as exc:
            raise QueuePublishNotSentError(
                "RabbitMQ task queue is unavailable before task publish."
            ) from exc
        # Publisher confirms keep the DB job row and RabbitMQ state in sync.
        # Pika's basic_publish does not have a reliable boolean return contract,
        # so we fail closed on broker-side publish exceptions instead.
        message_properties = pika.BasicProperties(
            delivery_mode=2,  # persistent
            content_type=_TOKEN_APPLICATION_JSON,
        )

        def _publish_message(routing_key: str, payload: bytes) -> None:
            ch.basic_publish(
                exchange=_EXCHANGE,
                routing_key=routing_key,
                body=payload,
                mandatory=True,
                properties=message_properties,
            )

        try:
            _publish_message(_queue_name(project_id), body)
        except Exception as exc:
            raise RuntimeError("publish not confirmed") from exc
        try:
            _publish_ready_hint(
                ch,
                project_id=project_id,
                job_id=job_id,
                task_id=task_id,
            )
        except Exception as exc:
            # The durable project message has already been confirmed. A ready
            # hint only accelerates scheduling; backlog recovery republishes it
            # when a worker next observes pending project work.
            logger.warning(
                "Ready hint publish failed after confirmed task publish job_id=%s project_id=%s: %s",
                job_id,
                project_id,
                exc,
            )
        logger.info(
            "Enqueued job_id=%s task_id=%s → queue=%s + ready=%s",
            job_id,
            task_id,
            _queue_name(project_id),
            _READY_QUEUE,
        )
    finally:
        if conn is not None:
            with contextlib.suppress(Exception):
                conn.close()


def enqueue_workflow_resume(
    project_id: Any,
    job_id: Any,
    task_id: str,
    thread_id: str,
    resume_revision: int,
    amqp_url: str | None = None,
) -> None:
    """Publish a durable approval-resume message to the owning project's worker queue."""
    project_id = _normalize_entity_id(project_id)
    job_id = _normalize_entity_id(job_id)
    clean_thread_id = str(thread_id or "").strip()
    if not clean_thread_id:
        raise ValueError("thread_id is required for workflow resume messages")
    clean_task_id = str(task_id or "").strip()
    if not clean_task_id:
        raise ValueError("task_id is required for workflow resume messages")
    try:
        clean_revision = int(resume_revision)
    except (TypeError, ValueError) as exc:
        raise ValueError("resume_revision is required for workflow resume messages") from exc
    if clean_revision <= 0:
        raise ValueError("resume_revision is required for workflow resume messages")

    message = {
        "message_type": "workflow_resume",
        "project_id": project_id,
        "job_id": job_id,
        "task_id": clean_task_id,
        "thread_id": clean_thread_id,
        "resume_revision": clean_revision,
    }
    body = json.dumps(message, default=_json_default).encode()

    conn = _connect(amqp_url)
    try:
        ch = conn.channel()
        _declare_queue(ch, project_id)
        _declare_ready_queue(ch)
        ch.confirm_delivery()
        message_properties = pika.BasicProperties(
            delivery_mode=2,
            content_type=_TOKEN_APPLICATION_JSON,
        )

        try:
            ch.basic_publish(
                exchange=_EXCHANGE,
                routing_key=_queue_name(project_id),
                body=body,
                mandatory=True,
                properties=message_properties,
            )
            _publish_ready_hint(
                ch,
                project_id=project_id,
                job_id=job_id,
                task_id=clean_task_id,
            )
        except Exception as exc:
            raise RuntimeError("workflow resume publish not confirmed") from exc
        logger.info(
            "Enqueued workflow resume job_id=%s task_id=%s revision=%s → queue=%s + ready=%s",
            job_id,
            clean_task_id,
            clean_revision,
            _queue_name(project_id),
            _READY_QUEUE,
        )
    finally:
        with contextlib.suppress(Exception):
            conn.close()
