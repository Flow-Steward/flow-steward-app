"""E2E tests for Events API.

Covers: EVT-01, EVT-02, EVT-03 — list events, get single event, redrive event.
"""

from __future__ import annotations

import os

import pytest

from core.application.tooling.testing.runtime_env import resolve_test_env
from tests.e2e.helpers import ensure_test_job, get, post_json

pytestmark = [pytest.mark.e2e]

BACKEND_ROLE = str(os.environ.get("E2E_BACKEND_ROLE", "admin") or "admin").strip().lower()
_BACKEND_ENV = resolve_test_env(os.environ, lane="backend", role=BACKEND_ROLE, include_dotenv=True)
PROJECT_ID = str(_BACKEND_ENV.project_id or "").strip()


@pytest.fixture(scope="module")
def server_available():
    try:
        resp = get("/health", timeout=5)
    except Exception as e:
        pytest.skip(f"Flow Steward server not available: {e}")
    if resp.status_code >= 500:
        pytest.skip(f"Flow Steward server unhealthy: {resp.status_code}")


@pytest.fixture(scope="module")
def seed_job(server_available) -> dict:
    """Ensure at least one job exists so that events are generated."""
    return ensure_test_job(PROJECT_ID)


def _get_first_event(seed_job) -> dict | None:
    """Fetch the first available event, or None."""
    resp = get("/api/events", params={"limit": 5})
    if resp.status_code != 200:
        return None
    data = resp.json()
    events = data if isinstance(data, list) else data.get("events") or []
    return events[0] if events else None


class TestEventsAPI:
    def test_events_list(self, server_available, seed_job):
        resp = get("/api/events")
        if resp.status_code == 404:
            pytest.skip("Events API not implemented")
        assert resp.status_code == 200
        data = resp.json()
        assert isinstance(data, (dict, list))
        events = data if isinstance(data, list) else data.get("events") or []
        assert isinstance(events, list)
        if events:
            row = events[0]
            expected_keys = {"event_type", "severity", "status", "title", "created_at"}
            missing = expected_keys.difference(set(row.keys()))
            assert not missing, f"events row missing frontend keys: {sorted(missing)}"
            assert ("id" in row) or ("event_id" in row)

    def test_events_list_with_params(self, server_available, seed_job):
        resp = get("/api/events", params={"limit": 5})
        if resp.status_code == 404:
            pytest.skip("Events API not implemented")
        assert resp.status_code == 200

    def test_event_get_nonexistent(self, server_available):
        resp = get("/api/events/999999")
        if resp.status_code == 404:
            return  # expected
        assert resp.status_code in (400, 404)

    def test_event_get_real(self, server_available, seed_job):
        event = _get_first_event(seed_job)
        if not event:
            pytest.skip("No events generated by seed job")
        eid = event.get("id") or event.get("event_id")
        if not eid:
            pytest.skip("Event has no id field")
        resp = get(f"/api/events/{eid}")
        assert resp.status_code == 200

    def test_event_redrive_nonexistent(self, server_available):
        resp = post_json("/api/events/999999/redrive", {})
        if resp.status_code == 404:
            return  # expected
        if BACKEND_ROLE == "viewer":
            assert resp.status_code == 403
            return
        assert resp.status_code in (400, 404, 409)

    def test_event_redrive_real(self, server_available, seed_job):
        event = _get_first_event(seed_job)
        if not event:
            pytest.skip("No events generated by seed job")
        eid = event.get("id") or event.get("event_id")
        if not eid:
            pytest.skip("Event has no id field")
        resp = post_json(f"/api/events/{eid}/redrive", {})
        # May succeed or reject depending on event state
        if BACKEND_ROLE == "viewer":
            assert resp.status_code == 403
            return
        assert resp.status_code in (200, 202, 400, 409, 422)
