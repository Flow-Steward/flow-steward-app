"""AC17-R121: a runtime nobody installed also has to have its long-lived secrets."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from core.infrastructure.config.env_registry import installer_generated_secret_names
from core.infrastructure.runtime.compact.process_spec import delivered_environment_names
from core.infrastructure.runtime.compact.runtime_secrets import (
    EXTERNALLY_OWNED_SECRETS,
    OperatorSecretWithdrawn,
    establish_runtime_secrets,
    self_minted_secret_names,
)


def test_which_secrets_the_runtime_owns_is_derived_from_what_already_declares_it() -> None:
    """Two existing declarations answer this; a third list would only drift from them.

    The environment registry knows every leaf secret the installer generates, and the
    supervisor's allowlists decide which variables a Compact role may inherit. A secret
    in both is one this runtime's processes read and nobody is going to hand it.
    """
    generated = installer_generated_secret_names()
    delivered = delivered_environment_names()

    assert self_minted_secret_names() == tuple(
        sorted((generated & delivered) - EXTERNALLY_OWNED_SECRETS)
    )
    # The exclusion does real work rather than naming something already absent.
    assert EXTERNALLY_OWNED_SECRETS <= (generated & delivered)
    # And it excludes only credentials an external service owns: a generated value
    # would authenticate against nothing, and on this profile the operator supplies
    # both inside FS_DB_DSN and RABBITMQ_URL.
    assert EXTERNALLY_OWNED_SECRETS == {"POSTGRES_PASSWORD", "RABBITMQ_PASS"}


def test_the_backup_key_falls_out_of_the_derivation_instead_of_being_special_cased() -> None:
    """It is generated by the installer and inherited by no Compact role.

    Backups run in a separate one-shot container that reads its own environment, so a
    value minted into the supervisor's would never reach them. Pinned because the
    tempting fix is to add it by name, which would produce a key nothing can use.
    """
    generated = installer_generated_secret_names()

    assert "FS_BACKUP_ENCRYPTION_KEY" in generated
    assert "FS_BACKUP_ENCRYPTION_KEY" not in delivered_environment_names()
    assert "FS_BACKUP_ENCRYPTION_KEY" not in self_minted_secret_names()


def test_the_first_action_on_an_uninstalled_runtime_now_works(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    """The defect and the fix, measured through the function that actually failed.

        ERROR [secret_codec] ENCRYPTION_KEY is not set; encrypted secret storage is
        unavailable.

    That is where a platform installation died: it came up, let an administrator in
    through the self-minted link, and could not perform the first action asked of it.
    """
    import os

    from core.infrastructure.security import secret_codec

    for name in self_minted_secret_names():
        monkeypatch.delenv(name, raising=False)

    with pytest.raises(RuntimeError, match="ENCRYPTION_KEY is required"):
        secret_codec.encrypt_secret("api-token")

    establish_runtime_secrets(
        state_path=tmp_path / "runtime-secrets.json",
        environment=os.environ,
    )

    # No key passed: the codec resolves it from the environment, which is how the
    # runtime's own processes reach it.
    ciphertext = secret_codec.encrypt_secret("api-token")
    assert secret_codec.decrypt_secret(ciphertext) == "api-token"


def test_a_restart_reads_the_same_keys_rather_than_making_new_ones(tmp_path: Path) -> None:
    """The difference from the one-time setup link, and the whole point.

    A key regenerated on the second start does not fail; it makes everything written
    under the first one unreadable, which is the quieter of the two failures.
    """
    state = tmp_path / "runtime-secrets.json"
    first: dict[str, str] = {}
    second: dict[str, str] = {}

    minted = establish_runtime_secrets(state_path=state, environment=first)
    restored = establish_runtime_secrets(state_path=state, environment=second)

    assert minted.minted == self_minted_secret_names()
    assert minted.reused == ()
    assert restored.minted == ()
    assert restored.reused == self_minted_secret_names()
    assert first == second
    assert all(len(value) >= 32 for value in first.values())
    assert len(set(first.values())) == len(first), "each secret must be its own value"


def test_the_state_file_is_readable_only_by_the_process_that_wrote_it(tmp_path: Path) -> None:
    state = tmp_path / "runtime-secrets.json"

    establish_runtime_secrets(state_path=state, environment={})

    assert state.stat().st_mode & 0o777 == 0o600
    payload = json.loads(state.read_text(encoding="utf-8"))
    assert payload["version"] == 1
    assert set(payload["minted"]) == set(self_minted_secret_names())


def test_what_the_operator_supplied_wins_and_is_not_copied_into_our_file(
    tmp_path: Path,
) -> None:
    """An installation configured deliberately must not acquire a second set of keys."""
    state = tmp_path / "runtime-secrets.json"
    environment = {"ENCRYPTION_KEY": "operator-chosen-master-key"}

    outcome = establish_runtime_secrets(state_path=state, environment=environment)

    assert "ENCRYPTION_KEY" in outcome.operator_supplied
    assert "ENCRYPTION_KEY" not in outcome.minted
    assert environment["ENCRYPTION_KEY"] == "operator-chosen-master-key"
    payload = json.loads(state.read_text(encoding="utf-8"))
    assert "ENCRYPTION_KEY" not in payload["minted"]
    assert "operator-chosen-master-key" not in state.read_text(encoding="utf-8")
    # The fingerprint is what lets the next start notice the key going away.
    assert "ENCRYPTION_KEY" in payload["fingerprints"]


def test_an_operator_key_that_disappears_stops_the_runtime_instead_of_replacing_it(
    tmp_path: Path,
) -> None:
    """The one transition where refusing is clearly right.

    Minting a replacement here would start cleanly and read nothing that was written
    before, with no message anywhere. The refusal names the variable and says how to
    accept the loss on purpose.
    """
    state = tmp_path / "runtime-secrets.json"
    establish_runtime_secrets(
        state_path=state, environment={"ENCRYPTION_KEY": "operator-chosen-master-key"}
    )

    with pytest.raises(OperatorSecretWithdrawn, match="ENCRYPTION_KEY was supplied"):
        establish_runtime_secrets(state_path=state, environment={})


def test_a_key_the_operator_changes_is_reported_and_not_refused(tmp_path: Path) -> None:
    """Rotation is a documented operation, so this says what changed and continues."""
    state = tmp_path / "runtime-secrets.json"
    establish_runtime_secrets(state_path=state, environment={"ENCRYPTION_KEY": "first-key"})

    outcome = establish_runtime_secrets(state_path=state, environment={"ENCRYPTION_KEY": "second"})

    assert outcome.rotated == ("ENCRYPTION_KEY",)
    # Everything else was minted on the first start and is read back on this one; only
    # the operator's own key changed, and that is reported rather than acted on.
    assert outcome.minted == ()
    assert outcome.reused == tuple(n for n in self_minted_secret_names() if n != "ENCRYPTION_KEY")


def test_a_state_file_this_version_cannot_read_is_not_overwritten(tmp_path: Path) -> None:
    """Replacing keys it cannot see is exactly the silent unreadable data to avoid."""
    state = tmp_path / "runtime-secrets.json"
    state.write_text(json.dumps({"version": 99, "minted": {}}), encoding="utf-8")

    with pytest.raises(OperatorSecretWithdrawn, match="not a runtime secret state file"):
        establish_runtime_secrets(state_path=state, environment={})

    assert json.loads(state.read_text(encoding="utf-8"))["version"] == 99


def test_an_empty_value_counts_as_absent(tmp_path: Path) -> None:
    """`${VAR:-}` in Compose always sets the key, so empty is not supplied.

    The same shape took the control plane down in AC17-R105; here it would have left
    the runtime believing the operator had chosen an empty encryption key.
    """
    state = tmp_path / "runtime-secrets.json"
    environment = {"ENCRYPTION_KEY": "   "}

    outcome = establish_runtime_secrets(state_path=state, environment=environment)

    assert "ENCRYPTION_KEY" in outcome.minted
    assert environment["ENCRYPTION_KEY"].strip()
